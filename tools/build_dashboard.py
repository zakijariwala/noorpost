#!/usr/bin/env python3
"""
The status dashboard: docs/status.html.

    python tools/build_dashboard.py        # write it
    python tools/build_dashboard.py --json # the same numbers, as data

Every number on the page is **measured from the repository**, not typed in.
That is the whole point: a hand-maintained status page is wrong within a week,
and a wrong status page is worse than none, because people act on it.

Where a number cannot be measured, the page says so rather than guessing.

Sources of every figure:

    TASKS.md                          phase checkboxes
    00-sources/metadata/claims.yaml   the TV -> V critical path
    00-sources/metadata/sources.yaml  editions, and what may be cited
    00-sources/source.db              corpus size, Arabic state (if built)
    00-foundations/citation-sheet.md  hadith card selection
    03-content/, 08-companions/,      what is actually written
    09-zines/, 04-art/artwork/
    README.md                         the blocking table, as its owner keeps it
    git                               last commit, and how old this build is

It is regenerated by tools/build_site.py, and by the GitHub Action on every
push, so it cannot drift from the repository it describes.
"""

import argparse
import datetime
import glob
import html
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs")


def read(path):
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        return ""
    with open(p, encoding="utf-8") as f:
        return f.read()


def git(*args):
    try:
        r = subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True, timeout=30)
        return r.stdout.decode("utf-8", "replace").strip() if r.returncode == 0 else ""
    except Exception:
        return ""


# --------------------------------------------------------------------------
# collectors
# --------------------------------------------------------------------------

def phases():
    """Checkbox counts per phase, straight off TASKS.md."""
    out = []
    current = None
    for line in read("TASKS.md").split("\n"):
        m = re.match(r"^## (Phase \d+[^\n]*)", line)
        if m:
            current = {"name": m.group(1).strip(), "done": 0, "open": 0}
            out.append(current)
            continue
        if current is None:
            continue
        if re.match(r"^\s*- \[x\]", line, re.I):
            current["done"] += 1
        elif re.match(r"^\s*- \[ \]", line):
            current["open"] += 1
    for p in out:
        p["total"] = p["done"] + p["open"]
        p["pct"] = round(100 * p["done"] / p["total"]) if p["total"] else None
    return out


def claims():
    """The critical path. TV -> V, from the claim database."""
    try:
        from sourcelib import metadata
        rows = metadata.load_claims()
    except Exception as e:
        return {"available": False, "why": str(e)}
    by = {}
    for c in rows:
        by[c.get("status")] = by.get(c.get("status"), 0) + 1
    total = len(rows)
    return {
        "available": True,
        "total": total,
        "by_status": by,
        "verified": by.get("V", 0),
        "to_verify": by.get("TV", 0),
        "pct_verified": round(100 * by.get("V", 0) / total) if total else 0,
    }


def sources():
    try:
        from sourcelib import metadata
        works, editions, _ = metadata.load_sources()
    except Exception as e:
        return {"available": False, "why": str(e)}
    by = {}
    for e in editions:
        by[e.get("status")] = by.get(e.get("status"), 0) + 1
    held = [e for e in editions if e.get("status") != "missing"]
    return {
        "available": True,
        "works": len(works),
        "editions": len(editions),
        "by_status": by,
        "fixed": by.get("fixed", 0),
        "missing": by.get("missing", 0),
        "page_citable": sum(1 for e in held if e.get("pagination") == "printed"),
        "no_sha256": [e["source_id"] for e in held if not e.get("sha256")],
        "no_translator": [e["source_id"] for e in held if not e.get("translator")],
    }


def corpus():
    """Only if source.db has been built — it is not tracked."""
    db_path = os.path.join(ROOT, "00-sources", "source.db")
    if not os.path.exists(db_path):
        return {"available": False,
                "why": "source.db is not tracked — run tools/build_source_corpus.py"}
    try:
        import sqlite3
        con = sqlite3.connect("file:%s?mode=ro" % db_path, uri=True)
        con.row_factory = sqlite3.Row
        one = lambda q: con.execute(q).fetchone()[0]
        out = {
            "available": True,
            "pages": one("SELECT COUNT(*) FROM pages"),
            "passages": one("SELECT COUNT(*) FROM passages"),
            "quotation_ready": one("SELECT COUNT(*) FROM passages WHERE quotation_ready=1"),
            "arabic_passages": one("SELECT COUNT(*) FROM passages WHERE arabic_verified=0"),
            "arabic_unusable_editions": [
                r["source_id"] for r in con.execute(
                    "SELECT source_id FROM editions WHERE arabic_extraction='unusable'")],
        }
        con.close()
        return out
    except Exception as e:
        return {"available": False, "why": str(e)}


def storefront():
    """The shop's switches, read from the same file the shop is built from."""
    try:
        import build_shop
        store, products = build_shop.load_products()
    except Exception as e:
        return {"available": False, "why": str(e)}
    wl = store.get("waitlist") or {}
    legal = store.get("legal") or {}
    return {
        "available": True,
        "skus": len(products),
        "priced": sum(1 for p in products if p.get("price") is not None),
        "sellable": sum(1 for p in products if p.get("status") == "available"),
        "provider": (store.get("provider") or "none"),
        "published": bool(store.get("published")),
        "waitlist_open": bool(wl.get("endpoint") or wl.get("email")),
        "legal_set": bool(legal.get("entity") and legal.get("contact")),
    }


def _words(text):
    return len(re.findall(r"[A-Za-z'’\-]+", text))


def denies_hadith_card(body):
    """True when the file states the rule overturned on 2026-08-14."""
    return bool(re.search(r"No hadith card", body, re.I))


def reads_as_carrying_card(body):
    """True when the file gives the entry a hadith card.

    The negation matters more than the phrase. Every companion file used to
    read "No hadith card. No event print." — the old rule — so a bare search
    for "hadith card" reported all thirty-nine as carrying one, which was the
    exact opposite of what the files said.
    """
    return bool(re.search(r"hadith card", body, re.I)) and not denies_hadith_card(body)


def content():
    """What is actually written, measured by looking at the files."""
    envelopes = []
    for n in range(1, 15):
        num = "%02d" % n
        src = ("01-pilot/envelope-03/letter.md" if num == "03"
               else "03-content/envelope-%s.md" % num)
        body = read(src)
        envelopes.append({"num": num, "exists": bool(body), "words": _words(body)})

    companions = []
    for p in sorted(glob.glob(os.path.join(ROOT, "08-companions", "*.md"))):
        name = os.path.basename(p)
        if name.upper().startswith("README"):
            continue
        body = read("08-companions/" + name)
        companions.append({
            "slug": name[:-3], "words": _words(body),
            "has_hadith_card": reads_as_carrying_card(body),
            "states_overturned_rule": denies_hadith_card(body)})

    zines = []
    for p in sorted(glob.glob(os.path.join(ROOT, "09-zines", "*.md"))):
        name = os.path.basename(p)
        if (name.upper().startswith("README") or "template" in name.lower()
                or "outline" in name.lower()):
            continue
        body = read("09-zines/" + name)
        # A zine is one sheet folded to eight pages. Eight written pages is the
        # structural definition of finished, and it is what can be measured —
        # a word threshold would just be a guess about quality.
        pages_written = len(re.findall(r"^## PAGE \d", body, re.M))
        zines.append({"slug": name[:-3], "pages": pages_written, "words": _words(body),
                      "full": pages_written >= 8})

    art = [f for f in glob.glob(os.path.join(ROOT, "04-art", "artwork", "*"))
           if os.path.splitext(f)[1].lower() in (".png", ".jpg", ".jpeg", ".webp", ".svg",
                                                 ".tif", ".tiff")]
    return {
        "envelopes": envelopes,
        "envelopes_written": sum(1 for e in envelopes if e["exists"]),
        "companions": companions,
        "companions_written": len(companions),
        "companions_with_hadith_card": sum(1 for c in companions if c["has_hadith_card"]),
        "companions_stating_overturned_rule": sum(1 for c in companions
                                                  if c["states_overturned_rule"]),
        "zines": zines,
        "zines_full": sum(1 for z in zines if z["full"]),
        "zines_total": len(zines),
        "artwork_files": len(art),
    }


def hadith_cards():
    """Box cards and companion cards, read off the citation sheet's own tables."""
    try:
        from import_citation_sheet import parse_sheet, SHEET, clean
        rows, _, _, _ = parse_sheet(SHEET)
    except Exception as e:
        return {"available": False, "why": str(e)}
    # by envelope, not by row: envelope 03's card appears both in its own
    # section and in the all-fourteen table
    box = [c for c in rows if c.get("item") == "hadith card"]

    # The companions line has its own table, which the importer deliberately
    # does not turn into claims — in the sheet's own words, "the theme is the
    # search brief, not the citation. Nothing here is a claim about a text."
    # So it is read here directly, and counted as slots rather than claims.
    companion = {"total": 0, "selected": 0, "blocked": 0}
    in_table = False
    for line in read("00-foundations/citation-sheet.md").split("\n"):
        if line.startswith("#"):
            in_table = False
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        sig = tuple(c.lower() for c in cells)
        if sig[:2] == ("entry", "points to") and "saying" in sig and "status" in sig:
            in_table = True
            continue
        if not in_table or len(cells) < 6 or set("".join(cells)) <= set("-: "):
            continue
        companion["total"] += 1
        if "BLOCKED" in cells[5].upper():
            companion["blocked"] += 1
        elif clean(cells[4]) not in ("", "—", "-", "–"):
            companion["selected"] += 1

    return {
        "available": True,
        "box_total": 14,
        "box_selected": len({c.get("env") for c in box if c.get("status") == "V"}),
        "box_blocked": len({c.get("env") for c in box
                            if c.get("status") == "needs-review"}),
        "companion_total": companion["total"] or 39,
        "companion_selected": companion["selected"],
        "companion_blocked": companion["blocked"],
    }


def blockers():
    """The README's own blocking table. One source of truth, not a second one."""
    body = read("README.md")
    m = re.search(r"## What is blocking, right now\s*\n(.*?)(?=\n## |\Z)", body, re.S)
    if not m:
        return {"available": False, "why": "the blocking table in README.md has moved"}
    out = []
    for line in m.group(1).split("\n"):
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3 or set("".join(cells)) <= set("-: "):
            continue
        if cells[0].lower() == "blocker":
            continue
        out.append({"blocker": cells[0], "blocks": cells[1], "owner": cells[2]})
    return {"available": True, "rows": out}


def build_info():
    return {
        "built_at": datetime.datetime.now(datetime.timezone.utc)
                             .replace(microsecond=0).isoformat(),
        "commit": git("rev-parse", "--short", "HEAD"),
        "commit_subject": git("log", "-1", "--format=%s"),
        "commit_date": git("log", "-1", "--format=%ad", "--date=short"),
        "branch": git("rev-parse", "--abbrev-ref", "HEAD"),
    }


def collect():
    return {
        "build": build_info(),
        "phases": phases(),
        "claims": claims(),
        "sources": sources(),
        "corpus": corpus(),
        "content": content(),
        "hadith_cards": hadith_cards(),
        "storefront": storefront(),
        "blockers": blockers(),
    }



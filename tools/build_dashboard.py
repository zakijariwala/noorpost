def bar(done, total, label=None):
    pct = round(100 * done / total) if total else 0
    lab = label or "%d / %d" % (done, total)
    return (f'<div class="meter" role="img" aria-label="{html.escape(lab)}">'
            f'<span style="width:{pct}%"></span></div>'
            f'<span class="meterlab">{html.escape(lab)}</span>')


def esc(x):
    return html.escape(str(x))


def render(d):
    S = []
    w = S.append

    b = d["build"]
    w('<section class="dashhero">')
    w("<h1>Status</h1>")
    w('<p class="lede">Every number here is measured from the repository at build '
      'time. Nothing on this page is typed in by hand, and nothing is an estimate. '
      'Where something cannot be measured, it says so.</p>')
    w('<p class="lede small">Built %s from <code>%s</code> on <code>%s</code> — '
      '%s</p>' % (esc(b["built_at"].replace("T", " ").replace("+00:00", " UTC")),
                  esc(b["commit"] or "unknown"), esc(b["branch"] or "?"),
                  esc(b["commit_subject"] or "")))
    w("</section>")

    # ---- the critical path -------------------------------------------
    c = d["claims"]
    hc = d["hadith_cards"]
    w('<section class="dash"><h2>The critical path — verification</h2>')
    if not c.get("available"):
        w('<p class="warn">Claim database unavailable: %s</p>' % esc(c.get("why")))
    else:
        w('<p class="sectionnote">A claim is <code>V</code> only when a person has '
          'opened the fixed edition at the named place. Nothing prints on '
          '<code>TV</code>.</p>')
        w('<div class="statrow">')
        w(stat("Claims verified", "%d / %d" % (c["verified"], c["total"]),
               bar(c["verified"], c["total"], "%d%% V" % c["pct_verified"])))
        w(stat("Still to verify", c["to_verify"], sub="status <code>TV</code>"))
        others = ", ".join("%s %d" % (k, v) for k, v in sorted(c["by_status"].items())
                           if k not in ("V", "TV"))
        w(stat("Other statuses", others or "—",
               sub="TRAD traditional · CONT contested · needs-review blocked"))
        w("</div>")
    if hc.get("available"):
        w('<div class="statrow">')
        w(stat("Box hadith cards", "%d / %d" % (hc["box_selected"], hc["box_total"]),
               bar(hc["box_selected"], hc["box_total"]),
               sub="%d blocked — no permitted source" % hc["box_blocked"]))
        w(stat("Companion hadith cards",
               "%d / %d" % (hc["companion_selected"], hc["companion_total"]),
               bar(hc["companion_selected"], hc["companion_total"]),
               sub="%d blocked — no permitted source, or no rule"
                   % hc["companion_blocked"]))
        w("</div>")
    w("</section>")

    # ---- what is written ---------------------------------------------
    ct = d["content"]
    w('<section class="dash"><h2>What is written</h2>')
    w('<p class="sectionnote">Measured by reading the files, not by a checklist.</p>')
    w('<div class="statrow">')
    w(stat("Envelope letters", "%d / 14" % ct["envelopes_written"],
           bar(ct["envelopes_written"], 14)))
    w(stat("Companion envelopes", "%d / 39" % ct["companions_written"],
           bar(ct["companions_written"], 39)))
    w(stat("Zines written in full", "%d / %d" % (ct["zines_full"], ct["zines_total"]),
           bar(ct["zines_full"], ct["zines_total"]),
           sub="all eight pages written"))
    w(stat("Illustrations", ct["artwork_files"],
           sub="image files in <code>04-art/artwork/</code>"
               + (" — prompts written, none run" if not ct["artwork_files"] else "")))
    w("</div>")
    if ct["companions_stating_overturned_rule"]:
        w('<p class="warn">The 2026-08-14 decision gave the companions line a hadith '
          'card and overturned the rule forbidding one. '
          '<strong>%d of %d companion files still state the overturned rule</strong> '
          '("No hadith card"), and %d carry one. Every published companion page '
          'therefore still shows the pre-decision item list.</p>'
          % (ct["companions_stating_overturned_rule"], ct["companions_written"],
             ct["companions_with_hadith_card"]))
    w("</section>")

    # ---- sources ------------------------------------------------------
    s = d["sources"]
    cp = d["corpus"]
    w('<section class="dash"><h2>The source library</h2>')
    if not s.get("available"):
        w('<p class="warn">Source metadata unavailable: %s</p>' % esc(s.get("why")))
    else:
        w('<div class="statrow">')
        w(stat("Editions fixed", "%d / %d" % (s["fixed"], s["editions"]),
               bar(s["fixed"], s["editions"]),
               sub=", ".join("%d %s" % (v, k) for k, v in sorted(s["by_status"].items()))))
        w(stat("Editions whose pages may be cited",
               "%d / %d" % (s["page_citable"], s["editions"] - s["missing"]),
               sub="every held edition is a web-generated or two-column PDF — "
                   "cite the work's own internal numbering"))
        w(stat("Editions not pinned by SHA-256", len(s["no_sha256"]),
               sub="an edition without a hash is not a fixed edition: "
                   + ", ".join("<code>%s</code>" % esc(x) for x in s["no_sha256"][:8])
               if s["no_sha256"] else "all pinned"))
        w(stat("Held with no translator credit", len(s["no_translator"]),
               sub=(", ".join("<code>%s</code>" % esc(x) for x in s["no_translator"])
                    + " — the project's own rule forbids citing them")
               if s["no_translator"] else "all credited"))
        w("</div>")
    if cp.get("available"):
        w('<div class="statrow">')
        w(stat("Pages indexed", "{:,}".format(cp["pages"])))
        w(stat("Passages", "{:,}".format(cp["passages"]),
               sub="%s fit to quote verbatim today" % "{:,}".format(cp["quotation_ready"])))
        w(stat("Arabic awaiting verification", "{:,}".format(cp["arabic_passages"]),
               sub="%d editions extract their Arabic as broken glyphs"
                   % len(cp["arabic_unusable_editions"])))
        w("</div>")
    else:
        w('<p class="sectionnote">Corpus statistics need <code>source.db</code>, which '
          'is not tracked (182 MB). %s</p>' % esc(cp.get("why", "")))
    w("</section>")

    # ---- storefront ---------------------------------------------------
    sf = d["storefront"]
    w('<section class="dash"><h2>Storefront</h2>')
    if not sf.get("available"):
        w('<p class="warn">Shop configuration unavailable: %s</p>' % esc(sf.get("why")))
    else:
        w('<p class="sectionnote">Three pages at <code>docs/shop/</code>, built from '
          '<code>06-commerce/products.yaml</code>. Read from that file, not typed here.</p>')
        w('<div class="statrow">')
        w(stat("SKUs defined", sf["skus"], sub="the five in the commerce plan"))
        w(stat("Priced", "%d / %d" % (sf["priced"], sf["skus"]),
               bar(sf["priced"], sf["skus"]),
               sub="no price exists in this repository yet"))
        w(stat("Payment provider", sf["provider"],
               sub="buy buttons stay inert until this is set"
                   if sf["provider"] == "none" else "wired"))
        w(stat("Search engines", "indexed" if sf["published"] else "noindex",
               sub="published: %s" % str(sf["published"]).lower()))
        w("</div>")
        if not sf["legal_set"]:
            w('<p class="warn">No seller entity, contact or privacy notice is set. '
              'An email address cannot be collected without them, so the waitlist '
              'renders a plain statement rather than a form.</p>')
    w("</section>")

    # ---- phases -------------------------------------------------------
    w('<section class="dash"><h2>Phases</h2>')
    w('<p class="sectionnote">Checkbox counts from <code>TASKS.md</code>. A ticked box '
      'is a claim by whoever ticked it, so this measures recorded progress, not '
      'finished work.</p>')
    w('<table class="dashtable"><thead><tr><th>Phase</th><th>Done</th>'
      '<th>Open</th><th></th></tr></thead><tbody>')
    for p in d["phases"]:
        w("<tr><td>%s</td><td>%d</td><td>%d</td><td>%s</td></tr>"
          % (esc(p["name"]), p["done"], p["open"],
             bar(p["done"], p["total"]) if p["total"] else "—"))
    w("</tbody></table></section>")

    # ---- blockers -----------------------------------------------------
    bl = d["blockers"]
    w('<section class="dash"><h2>Blocking, right now</h2>')
    if not bl.get("available"):
        w('<p class="warn">%s</p>' % esc(bl.get("why")))
    else:
        w('<p class="sectionnote">Read from the table in <code>README.md</code>, so '
          'there is one list and not two.</p>')
        w('<table class="dashtable"><thead><tr><th>Blocker</th><th>Blocks</th>'
          '<th>Owner</th></tr></thead><tbody>')
        for r in bl["rows"]:
            w("<tr><td>%s</td><td>%s</td><td>%s</td></tr>"
              % (md_inline(r["blocker"]), md_inline(r["blocks"]), md_inline(r["owner"])))
        w("</tbody></table>")
    w("</section>")
    return "\n".join(S)


def md_inline(text):
    """The little markdown the README tables use, and nothing else."""
    t = html.escape(text)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*(.+?)\*", r"<em>\1</em>", t)
    return t


def stat(label, value, meter=None, sub=None):
    parts = ['<div class="stat">', '<p class="statlab">%s</p>' % esc(label),
             '<p class="statval">%s</p>' % (value if isinstance(value, str)
                                            and "<" in str(value) else esc(value))]
    if meter:
        parts.append('<p class="statmeter">%s</p>' % meter)
    if sub:
        parts.append('<p class="statsub">%s</p>' % sub)
    parts.append("</div>")
    return "".join(parts)


def write_page():
    from build_site import page
    d = collect()
    os.makedirs(OUT, exist_ok=True)
    dest = os.path.join(OUT, "status.html")
    with open(dest, "w", encoding="utf-8") as f:
        f.write(page("Status", "", render(d)))
    return dest


def main_from_site():
    """Called by build_site.build() so one command builds the whole site."""
    write_page()
    print("  status page built from live repository state")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    d = collect()
    if args.json:
        print(json.dumps(d, indent=2, ensure_ascii=False))
        return 0

    write_page()
    print("built docs/status.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
